"""Generate src/tables_host.h from RustingStrata's src/quant/tables.rs.

Strata prepends these arrays to `kernels.cu` as a source string (`source_with()` in src/cuda/mod.rs);
on the host side the CPU reference dequantizers need the same arrays, so they are emitted as constexpr
C++ instead of being retyped. Run this after unpacking a new Strata version:

    set STRATA_SRC_V125=<RustingStrata 1.2.5 source root>
    python tools/gen_tables.py

STRATA_SRC_V125 must be a checkout/unpacked copy of RustingStrata 1.2.5 (the directory that contains
src/quant/tables.rs). The generated file is already committed; this tool is only needed to regenerate
it from a different release.

The input file carries the header "Generated by tools/gen_tables.py from llama.cpp ggml-common.h
(MIT License, ggml authors)" and the values are unchanged.
"""

from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC_ROOT = os.environ.get("STRATA_SRC_V125", "")
SRC = os.path.join(SRC_ROOT, "src", "quant", "tables.rs") if SRC_ROOT else ""
OUT = os.path.join(ROOT, "src", "tables_host.h")

CTYPE = {"u64": "uint64_t", "u32": "uint32_t", "u8": "uint8_t", "i8": "int8_t"}

DECL = re.compile(r"^pub static (\w+): \[(\w+); (\d+)\] = \[(.*)\];\s*$")


def parse(path: str):
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = DECL.match(line.strip())
            if not m:
                continue
            name, rty, count, body = m.groups()
            if rty not in CTYPE:
                raise SystemExit(f"{name}: unmapped Rust type {rty}")
            nums = [v.strip() for v in body.split(",") if v.strip()]
            if len(nums) != int(count):
                raise SystemExit(f"{name}: expected {count} values, found {len(nums)}")
            out.append((name, rty, int(count), nums))
    return out


def emit(tables):
    lines = [
        "// Generated by tools/gen_tables.py from RustingStrata 1.2.5 src/quant/tables.rs.",
        "// The values come from llama.cpp ggml-common.h (MIT License, ggml authors) via RustingStrata.",
        "// Do not edit: rerun the generator.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace strata::tables {",
        "",
    ]
    for name, rty, count, nums in tables:
        cty = CTYPE[rty]
        body = ",".join(nums)
        lines.append(f"inline constexpr {cty} {name}[{count}] = {{{body}}};")
    lines += ["", "}  // namespace strata::tables", ""]
    return "\n".join(lines)


def main() -> int:
    if not SRC:
        raise SystemExit("set STRATA_SRC_V125=<RustingStrata 1.2.5 source root> (it must contain "
                         "src/quant/tables.rs) before running this tool")
    if not os.path.isfile(SRC):
        raise SystemExit(f"missing {SRC}; unpack the Strata 1.2.5 source and set STRATA_SRC_V125")
    tables = parse(SRC)
    if not tables:
        raise SystemExit(f"no arrays parsed from {SRC}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(emit(tables))
    print(f"wrote {OUT}: {len(tables)} tables ({', '.join(n for n, _, _, _ in tables)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
