"""Embed kernel source files as C byte arrays for the strata-cpp build.

Usage: python tools/embed_kernels.py OUT.cpp NAME=PATH [NAME=PATH ...]

Writes OUT.cpp defining, in namespace strata::embed, for each NAME:
    extern const unsigned char NAME[] = {...};
    extern const size_t NAMELen = <byte count>;
The bytes are the file contents exactly (Strata's include_str! reads the same bytes). Byte arrays avoid the
MSVC string-literal length limit for kernels.cu (about 169 KB).

Part of strata-cpp, a C++ port of RustingStrata by Vasyl Trefilov (RustingStrata License 1.0, see
LICENSE-RustingStrata.md).
"""

import pathlib
import sys


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    out = pathlib.Path(sys.argv[1])
    lines = [
        "// generated by tools/embed_kernels.py from kernels/ (do not edit)",
        "#include <cstddef>",
        "namespace strata::embed {",
    ]
    for arg in sys.argv[2:]:
        name, _, path = arg.partition("=")
        if not name or not path:
            print(f"bad argument {arg!r}, expected NAME=PATH", file=sys.stderr)
            return 2
        data = pathlib.Path(path).read_bytes()
        body = ",".join(str(b) for b in data)
        lines.append(f"extern const unsigned char {name}[] = {{{body}}};")
        lines.append(f"extern const size_t {name}Len = {len(data)};")
    lines.append("}  // namespace strata::embed")
    text = "\n".join(lines) + "\n"
    tmp = out.with_suffix(out.suffix + ".tmp")
    tmp.write_text(text, encoding="ascii")
    tmp.replace(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
